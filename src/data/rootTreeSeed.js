/**
 * Hàm seed — kiểm tra và insert nếu chưa có.
 */
async function seedRootTree() {
  const { getRootTreeModel } = require('../models/rootTree.model');
  const logger = require('../utils/logger');

  try {
    const RootTree = getRootTreeModel();
    const existingCount = await RootTree.countDocuments();

    if (existingCount > 0) {
      logger.info(`🌳 Cây gốc đã có ${existingCount} nhánh — bỏ qua seed`);
      return { seeded: 0, existing: existingCount };
    }

    let inserted = 0;
    for (const nhanh of SEED_NHANH) {
      try {
        await RootTree.create(nhanh);
        inserted++;
      } catch (err) {
        logger.warn(`Seed nhánh ${nhanh.id} lỗi: ${err.message}`);
      }
    }

    logger.success(`✅ Đã seed ${inserted} nhánh vào cây gốc`);
    return { seeded: inserted, existing: 0 };
  } catch (err) {
    logger.error('Seed cây gốc lỗi:', err.message);
    throw err;
  }
}

module.exports = { SEED_NHANH, seedRootTree };